-- ============================================================
-- AP3 Agriculture Information System — Supabase Schema
-- ============================================================
-- Run this in the Supabase SQL Editor (Dashboard -> SQL Editor -> New query)
--
-- Design notes:
--   * Every controlled value (category, season, soil, irrigation, status,
--     grade, remark) lives in its own lookup table. Application dropdowns
--     store the lookup ID and display the descriptive label.
--   * CROP_SPECIES holds the crop name and category; CROP holds a variety
--     of that species plus its growing period and recommended season.
--     This removes the transitive dependency
--     crop_id -> variety -> crop_name -> crop_category.
--   * HARVEST stores only remark_id; the free-text remarks column was
--     removed so a remark has a single source of truth.
-- ============================================================

-- ------------------------------------------------------------
-- Lookup tables (controlled dropdown values)
-- ------------------------------------------------------------

CREATE TABLE public.crop_category (
    crop_category_id  integer PRIMARY KEY,
    category_name     character varying(50) NOT NULL UNIQUE
);

CREATE TABLE public.season (
    season_id         integer PRIMARY KEY,
    season_name       character varying(30) NOT NULL UNIQUE
);

CREATE TABLE public.soil_type (
    soil_type_id      integer PRIMARY KEY,
    type_name         character varying(50) NOT NULL UNIQUE
);

CREATE TABLE public.irrigation_type (
    irrigation_type_id integer PRIMARY KEY,
    type_name          character varying(50) NOT NULL UNIQUE
);

CREATE TABLE public.planting_status (
    planting_status_id integer PRIMARY KEY,
    status_name        character varying(30) NOT NULL UNIQUE
);

CREATE TABLE public.quality_grade (
    quality_grade_id  integer PRIMARY KEY,
    grade_name        character varying(30) NOT NULL UNIQUE
);

CREATE TABLE public.harvest_remarks (
    remark_id           integer PRIMARY KEY,
    remark_description  character varying(100) NOT NULL
);

-- ------------------------------------------------------------
-- Core tables
-- ------------------------------------------------------------

CREATE TABLE public.species (
    species_id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    crop_name          character varying(80) NOT NULL UNIQUE,
    crop_category_id   integer NOT NULL REFERENCES public.crop_category (crop_category_id)
);

CREATE TABLE public.crop (
    crop_id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    species_id            integer NOT NULL REFERENCES public.species (species_id),
    variety               character varying(80) NOT NULL,
    growing_period_days   integer NOT NULL CHECK (growing_period_days > 0),
    season_id             integer NOT NULL REFERENCES public.season (season_id),
    CONSTRAINT crop_variety_unique UNIQUE (species_id, variety)
);

CREATE TABLE public.farmer (
    farmer_id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name        character varying(50) NOT NULL,
    last_name         character varying(50) NOT NULL,
    contact_number    character varying(20),
    address           character varying(150),
    date_registered   date NOT NULL DEFAULT CURRENT_DATE,
    created_at        timestamptz NOT NULL DEFAULT NOW(),
    updated_at        timestamptz NOT NULL DEFAULT NOW()
);

CREATE TABLE public.farm (
    farm_id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmer_id          integer NOT NULL REFERENCES public.farmer (farmer_id),
    farm_name          character varying(100) NOT NULL,
    location           character varying(150) NOT NULL,
    area_hectares      numeric(8,2) NOT NULL CHECK (area_hectares > 0),
    soil_type_id       integer NOT NULL REFERENCES public.soil_type (soil_type_id),
    irrigation_type_id integer NOT NULL REFERENCES public.irrigation_type (irrigation_type_id),
    created_at         timestamptz NOT NULL DEFAULT NOW(),
    updated_at         timestamptz NOT NULL DEFAULT NOW()
);

CREATE TABLE public.planting (
    planting_id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farm_id                integer NOT NULL REFERENCES public.farm (farm_id),
    crop_id                integer NOT NULL REFERENCES public.crop (crop_id),
    planting_date          date NOT NULL,
    area_planted           numeric(8,2) NOT NULL CHECK (area_planted > 0),
    seed_quantity          numeric(8,2) NOT NULL CHECK (seed_quantity >= 0),
    expected_harvest_date  date NOT NULL,
    planting_status_id     integer NOT NULL REFERENCES public.planting_status (planting_status_id),
    created_at             timestamptz NOT NULL DEFAULT NOW(),
    updated_at             timestamptz NOT NULL DEFAULT NOW(),
    CONSTRAINT planting_expected_after_planting CHECK (expected_harvest_date >= planting_date)
);

CREATE TABLE public.harvest (
    harvest_id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    planting_id           integer NOT NULL REFERENCES public.planting (planting_id),
    harvest_date          date NOT NULL,
    quantity_kg           numeric(10,2) NOT NULL CHECK (quantity_kg > 0),
    selling_price_per_kg  numeric(10,2) NOT NULL CHECK (selling_price_per_kg >= 0),
    quality_grade_id      integer NOT NULL REFERENCES public.quality_grade (quality_grade_id),
    remark_id             integer REFERENCES public.harvest_remarks (remark_id),
    created_at            timestamptz NOT NULL DEFAULT NOW(),
    updated_at            timestamptz NOT NULL DEFAULT NOW()
);

