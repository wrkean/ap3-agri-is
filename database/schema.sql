CREATE TABLE public.harvest_remarks (
    remark_id           integer PRIMARY KEY,
    remark_description  character varying(100) NOT NULL
);

-- ------------------------------------------------------------
-- Core tables
-- ------------------------------------------------------------

CREATE TABLE public.crop (
    crop_id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    crop_name             character varying(80) NOT NULL,
    variety               character varying(80) NOT NULL,
    crop_category         character varying(50) NOT NULL,
    growing_period_days   integer NOT NULL,
    recommended_season    character varying(30) NOT NULL
);

CREATE TABLE public.farmer (
    farmer_id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name        character varying(50) NOT NULL,
    last_name         character varying(50) NOT NULL,
    contact_number    character varying(20),
    address           character varying(150),
    date_registered   date NOT NULL DEFAULT CURRENT_DATE,
    created_at        timestamptz NOT NULL DEFAULT NOW(),
    updated_at        timestamptz NOT NULL DEFAULT NOW()
);

CREATE TABLE public.farm (
    farm_id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmer_id         integer NOT NULL REFERENCES public.farmer (farmer_id),
    farm_name         character varying(100) NOT NULL,
    location          character varying(150) NOT NULL,
    area_hectares     numeric(8,2) NOT NULL CHECK (area_hectares > 0),
    soil_type         character varying(50) NOT NULL,
    irrigation_type   character varying(50) NOT NULL,
    created_at        timestamptz NOT NULL DEFAULT NOW(),
    updated_at        timestamptz NOT NULL DEFAULT NOW()
);

CREATE TABLE public.planting (
    planting_id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farm_id                integer NOT NULL REFERENCES public.farm (farm_id),
    crop_id                integer NOT NULL REFERENCES public.crop (crop_id),
    planting_date          date NOT NULL,
    area_planted           numeric(8,2) NOT NULL CHECK (area_planted > 0),
    seed_quantity          numeric(8,2) NOT NULL CHECK (seed_quantity >= 0),
    expected_harvest_date  date NOT NULL,
    status                 character varying(30) NOT NULL DEFAULT 'Growing',
    created_at             timestamptz NOT NULL DEFAULT NOW(),
    updated_at             timestamptz NOT NULL DEFAULT NOW(),
    CONSTRAINT planting_expected_after_planting CHECK (expected_harvest_date >= planting_date)
);

CREATE TABLE public.harvest (
    harvest_id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    planting_id           integer NOT NULL REFERENCES public.planting (planting_id),
    harvest_date          date NOT NULL,
    quantity_kg           numeric(10,2) NOT NULL CHECK (quantity_kg > 0),
    selling_price_per_kg  numeric(10,2) NOT NULL CHECK (selling_price_per_kg >= 0),
    quality_grade         character varying(30) NOT NULL,
    remark_id             integer REFERENCES public.harvest_remarks (remark_id),
    remarks               character varying(200),
    created_at            timestamptz NOT NULL DEFAULT NOW(),
    updated_at            timestamptz NOT NULL DEFAULT NOW()
);

